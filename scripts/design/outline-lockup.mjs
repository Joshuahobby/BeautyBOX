#!/usr/bin/env node
// Builds src/design/brand/BeautyBox_Platform_Hub_Lockup_Outlined.svg from the supplied lockup
// (handoff assets/brand). The supplied file sets its "BeautyBox" wordmark as live SVG text in
// Inter 700, and an <img> cannot load web fonts, so each browser drew it in whatever fallback
// it had. This replaces only that <text> element with the same words as outlines, shaped by
// HarfBuzz (the shaper Chrome uses) from Inter's variable font at the text's weight and at the
// optical size Chrome picks for it (font-optical-sizing: auto, the font size clamped to the
// opsz axis). The icon and everything else in the file are copied unchanged.
//
// Usage: node scripts/design/outline-lockup.mjs <Inter latin variable WOFF2>
// The font used: https://fonts.gstatic.com/s/inter/v20/UcC73FwrK3iLTeHuS_nVMrMxCp50SjIa1ZL7.woff2
// (Google Fonts, Inter v20, SIL OFL 1.1), the same file the opening film loads. Only the
// outlines are kept in this repository, not the font.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { Blob, Buffer as ShapeBuffer, Face, Font, Variation, shape } from "harfbuzzjs";

const require = createRequire(import.meta.url);
const { decompress } = require("wawoff2");

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const source = path.join(root, "src", "design", "brand", "BeautyBox_Platform_Hub_Lockup.svg");
const target = path.join(root, "src", "design", "brand", "BeautyBox_Platform_Hub_Lockup_Outlined.svg");

const fontPath = process.argv[2];
if (!fontPath) {
  console.error("usage: node scripts/design/outline-lockup.mjs <Inter latin variable WOFF2>");
  process.exit(1);
}

const svg = fs.readFileSync(source, "utf8");
const textElement = /<text ([^>]*)>([^<]*)<tspan ([^>]*)>([^<]*)<\/tspan><\/text>/.exec(svg);
if (!textElement) throw new Error("the supplied lockup no longer has the expected <text>Beauty<tspan>Box</tspan></text> wordmark");
const [whole, textAttrs, first, tspanAttrs, second] = textElement;
const attr = (attrs, name) => {
  const value = new RegExp(`(?:^|\\s)${name}="([^"]*)"`).exec(attrs)?.[1];
  if (value === undefined) throw new Error(`the wordmark has no ${name} attribute`);
  return value;
};
const family = attr(textAttrs, "font-family");
if (!/^Inter\b/.test(family)) throw new Error(`the wordmark asks for "${family}", not Inter`);
const x0 = Number(attr(textAttrs, "x"));
const baseline = Number(attr(textAttrs, "y"));
const size = Number(attr(textAttrs, "font-size"));
const weight = Number(attr(textAttrs, "font-weight"));
const spacing = Number(attr(textAttrs, "letter-spacing"));
const runs = [
  { text: first, fill: attr(textAttrs, "fill") },
  { text: second, fill: attr(tspanAttrs, "fill") },
];

const face = new Face(new Blob(await decompress(fs.readFileSync(fontPath))));
const axes = face.getAxisInfos();
if (!axes.wght) throw new Error("the font is not Inter's variable font (no wght axis)");
const clamp = (value, axis) => Math.min(Math.max(value, axis.min), axis.max);
const variations = [new Variation("wght", clamp(weight, axes.wght))];
if (axes.opsz) variations.push(new Variation("opsz", clamp(size, axes.opsz)));
const font = new Font(face);
font.setVariations(variations);

// Shape the whole word at once, as the browser does across the <tspan>, then colour glyphs by
// the run their character belongs to.
const words = runs.map((r) => r.text).join("");
const buffer = new ShapeBuffer();
buffer.addText(words);
buffer.guessSegmentProperties();
shape(font, buffer);

const scale = size / face.upem;
const round = (n) => Number(n.toFixed(2));
const paths = runs.map(() => []);
let pen = x0;
for (const glyph of buffer.getGlyphInfosAndPositions()) {
  const run = glyph.cluster < first.length ? 0 : 1;
  const ox = pen + (glyph.xOffset ?? 0) * scale;
  const oy = baseline - (glyph.yOffset ?? 0) * scale;
  const point = (fx, fy) => `${round(ox + fx * scale)} ${round(oy - fy * scale)}`;
  for (const { type, values: v } of font.glyphToJson(glyph.codepoint)) {
    if (type === "Z") paths[run].push("Z");
    else if (type === "M" || type === "L") paths[run].push(`${type}${point(v[0], v[1])}`);
    else if (type === "Q") paths[run].push(`Q${point(v[0], v[1])} ${point(v[2], v[3])}`);
    else if (type === "C") paths[run].push(`C${point(v[0], v[1])} ${point(v[2], v[3])} ${point(v[4], v[5])}`);
    else throw new Error(`unexpected path command ${type}`);
  }
  // letter-spacing follows every character, as browsers apply it.
  pen += (glyph.xAdvance ?? 0) * scale + spacing;
}

const settings = variations.map((v) => `${v.tag} ${v.value}`).join(", ");
const outlines = runs.map((run, i) => `<path d="${paths[i].join("")}" fill="${run.fill}"/>`).join("\n  ");
const output = svg
  .replace(/^(<\?xml[^>]*\?>\r?\n)/, `$1<!-- Generated by scripts/design/outline-lockup.mjs from BeautyBox_Platform_Hub_Lockup.svg: the wordmark as Inter outlines (${settings}). Edit the supplied file and run the script again; do not edit this one. -->\n`)
  .replace(whole, outlines);
fs.writeFileSync(target, output);
console.log(`wrote ${path.relative(root, target)} (${settings}; ${words.length} characters, ${(output.length / 1024).toFixed(1)} KiB)`);
