#!/usr/bin/env node
// One-command local setup: project-local PostgreSQL cluster, role bootstrap, env files
// with freshly generated local-only secrets, migrations, simulated provider schema
// and the demo fixture catalog. Safe to re-run; never touches non-BeautyBOX data.
//
//   npm run setup:local            (dev + test databases)
//   npm run setup:local -- --reset (recreate both databases from empty)
import { spawnSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { writePrivateFile } from "./lib/private-file.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const reset = process.argv.includes("--reset");
const node = process.execPath;
const pg = path.join(root, "scripts", "db", "local-postgres.mjs");

function run(cmd, args, env = {}) {
  const r = spawnSync(cmd, args, { cwd: root, stdio: "inherit", env: { ...process.env, ...env }, shell: false });
  if (r.status !== 0) {
    console.error(`[setup] failed: ${path.basename(cmd)} ${args.join(" ")}`);
    process.exit(r.status ?? 1);
  }
}

function capture(cmd, args) {
  const r = spawnSync(cmd, args, { cwd: root, encoding: "utf8" });
  if (r.status !== 0) {
    console.error(r.stderr);
    process.exit(1);
  }
  return r.stdout;
}

run(node, [pg, "setup"]);
if (reset) {
  run(node, [pg, "reset-db", "beautybox_dev"]);
  run(node, [pg, "reset-db", "beautybox_test"]);
}
const urls = Object.fromEntries(
  capture(node, [pg, "env"])
    .trim()
    .split(/\r?\n/)
    .map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1)]),
);

const secret = (n = 32) => randomBytes(n).toString("base64url");

function writeEnvFile(file, values) {
  const target = path.join(root, file);
  let existing = {};
  if (fs.existsSync(target)) {
    for (const line of fs.readFileSync(target, "utf8").split(/\r?\n/)) {
      const i = line.indexOf("=");
      if (i > 0 && !line.startsWith("#")) existing[line.slice(0, i)] = line.slice(i + 1);
    }
  }
  // Keep previously generated secrets so encrypted local data stays readable.
  // Keep values the developer added (e.g. Supabase dev project settings) across re-runs.
  const merged = { ...existing, ...values };
  for (const k of ["DATA_ENCRYPTION_KEY", "TOKEN_HASH_SECRET", "WORKER_SECRET"]) if (existing[k]) merged[k] = existing[k];
  const body = [
    "# Generated by scripts/setup-local.mjs for LOCAL/TEST use only. Never commit; never reuse in staging/production.",
    ...Object.entries(merged).map(([k, v]) => `${k}=${v}`),
    "",
  ].join("\n");
  writePrivateFile(target, body);
  console.log(`[setup] wrote ${file}`);
}

const common = {
  DATA_ENCRYPTION_KEY: randomBytes(32).toString("base64"),
  TOKEN_HASH_SECRET: secret(),
  WORKER_SECRET: secret(),
  PAYMENT_PROVIDER: "fake",
  ROUTING_PROVIDER: "fake",
  SMS_PROVIDER: "fake",
  DEMO_CATALOG_VISIBLE: "true",
};

writeEnvFile(".env.local", {
  APP_ENV: "local",
  APP_ORIGIN: "http://localhost:3000",
  DATABASE_URL: urls.DATABASE_URL,
  MIGRATION_DATABASE_URL: urls.MIGRATION_DATABASE_URL,
  ...common,
});
writeEnvFile(".env.test", {
  APP_ENV: "test",
  APP_ORIGIN: "http://localhost:3100",
  DATABASE_URL: urls.TEST_DATABASE_URL,
  MIGRATION_DATABASE_URL: urls.TEST_MIGRATION_DATABASE_URL,
  ...common,
});

// Bootstrap roles/schema, migrate, simulated provider, deployment profile, fixtures.
for (const [envFile, db, profile] of [
  [".env.local", "beautybox_dev", "LOCAL"],
  [".env.test", "beautybox_test", "TEST"],
]) {
  run(node, [path.join(root, "scripts", "db", "prepare-database.mjs"), envFile, db, profile]);
}
console.log("[setup] done. Start the app with: npm run dev   (and the job worker with: npm run worker)");
